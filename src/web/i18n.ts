import { ref } from 'vue';

/**
 * The UI's two languages: Serbian (Latin script, the default) and English.
 * A small dictionary rather than vue-i18n - the app has one screenful of
 * text per view and no pluralization beyond Serbian's three noun forms,
 * which `plural` covers.
 *
 * `t` reads the reactive `locale`, so a template or computed that calls it
 * re-renders when the language is switched. The choice is remembered per
 * browser.
 */
export type Locale = 'sr' | 'en';

export const LOCALES: Array<{ value: Locale; label: string }> = [
  { value: 'sr', label: 'SR' },
  { value: 'en', label: 'EN' },
];

const STORAGE_KEY = 'locale';

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'sr' || saved === 'en') return saved;
  } catch {
    // Storage unavailable - the default is fine.
  }
  return 'sr';
}

export const locale = ref<Locale>(initialLocale());

export function setLocale(value: Locale): void {
  locale.value = value;
  try {
    localStorage.setItem(STORAGE_KEY, value);
  } catch {
    // Ignore.
  }
  if (typeof document !== 'undefined') document.documentElement.lang = value === 'sr' ? 'sr-Latn' : 'en';
}

/** BCP 47 tag for dates and numbers in the current language. */
export function intlLocale(): string {
  return locale.value === 'sr' ? 'sr-Latn-RS' : 'en-GB';
}

