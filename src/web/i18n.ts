const MESSAGES: Record<Locale, Record<Key, string>> = { sr, en };

export type MessageKey = Key;

/** The text for `key` in the current language, with `{name}` placeholders filled from `params`. */
export function t(key: Key, params?: Params): string {
  const template = MESSAGES[locale.value][key] ?? MESSAGES.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

/** Like `t`, for keys built at runtime (e.g. from a server value); falls back to `fallback` for an unknown one. */
export function tDynamic(key: string, fallback: string, params?: Params): string {
  return key in MESSAGES.en ? t(key as Key, params) : fallback;
}

export function formatNumber(value: number, options?: Intl.NumberFormatOptions): string {
  return value.toLocaleString(intlLocale(), options);
}
